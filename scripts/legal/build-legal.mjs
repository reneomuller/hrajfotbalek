/**
 * Rebuilds what the site serves from the lawyer's documents.
 *
 *   node scripts/legal/build-legal.mjs
 *
 * Run it whenever a file in `content/legal/original/` or
 * `content/legal/substitutions.json` changes. It writes two things:
 *
 * 1. `lib/content/legalOriginals.generated.ts` — the three HTML files embedded
 *    as strings. The pages import them rather than reading `content/` at
 *    request time, because Next only ships files a route IMPORTS; a runtime
 *    `readFileSync` needs an `outputFileTracingIncludes` entry per route, and
 *    forgetting one is a 500 in production only. A unit test fails if this
 *    file and the originals ever disagree, so a forgotten rebuild is caught.
 *
 * 2. `public/legal/obchodni-podminky.pdf` — the terms as a PDF, which the
 *    lawyer's brief asks for alongside the HTML page and which the purchase
 *    confirmation email attaches. Printed by Chromium from the lawyer's own
 *    HTML, which carries A4 print rules, with the documented substitutions
 *    applied, so the PDF and the page say the same words.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { applyLegalSubstitutions } from "../../lib/content/legalSubstitutions.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const ORIGINALS = path.join(root, "content", "legal", "original");
const DOCUMENTS = ["obchodni-podminky", "zasady-zpracovani-osobnich-udaju", "zasady-pouzivani-cookies"];
const PDF_DOCUMENT = "obchodni-podminky";

const { rules } = JSON.parse(
  readFileSync(path.join(root, "content", "legal", "substitutions.json"), "utf8"),
);

const originals = Object.fromEntries(
  DOCUMENTS.map((id) => [id, readFileSync(path.join(ORIGINALS, `${id}.html`), "utf8")]),
);

const generated = [
  "// GENERATED by scripts/legal/build-legal.mjs from content/legal/original/*.html.",
  "// Do not edit: change the original or the substitutions and rebuild.",
  "",
  "export const LEGAL_ORIGINALS = {",
  ...DOCUMENTS.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(originals[id])},`),
  "} as const;",
  "",
  "export type LegalOriginalId = keyof typeof LEGAL_ORIGINALS;",
  "",
].join("\n");

writeFileSync(path.join(root, "lib", "content", "legalOriginals.generated.ts"), generated);
console.log("wrote lib/content/legalOriginals.generated.ts");

const html = applyLegalSubstitutions(PDF_DOCUMENT, originals[PDF_DOCUMENT], rules);
const outDir = path.join(root, "public", "legal");
mkdirSync(outDir, { recursive: true });

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  await page.setContent(html, { waitUntil: "load" });
  await page.pdf({
    path: path.join(outDir, `${PDF_DOCUMENT}.pdf`),
    preferCSSPageSize: true,
    printBackground: true,
  });
} finally {
  await browser.close();
}
console.log(`wrote public/legal/${PDF_DOCUMENT}.pdf`);

-- -----------------------------------------------------------------------------
-- 1. games.game_number
--
-- BACKFILLED IN CREATION ORDER, then an identity takes over from the next free
-- number. Production was reset on 2026-10-26, so its first game will be 1.
--
-- READ THROUGH THE EXISTING TABLE GRANT: `anon` and `authenticated` hold
-- SELECT on the whole of `games`, which covers a new column — the
-- verification block asserts it rather than assuming it, because a missing
-- grant here reads as "that game does not exist".
-- -----------------------------------------------------------------------------

alter table public.games add column if not exists game_number integer;

with numbered as (
  select id,
         coalesce((select max(game_number) from public.games), 0)
           + row_number() over (order by created_at, id) as n
    from public.games
   where game_number is null
)
update public.games g
   set game_number = numbered.n
  from numbered
 where g.id = numbered.id;

-- NOT NULL first: Postgres will not make a nullable column an identity.
alter table public.games alter column game_number set not null;

do $$
declare v_next integer;
begin
  if not exists (select 1 from information_schema.columns
                  where table_schema = 'public' and table_name = 'games'
                    and column_name = 'game_number' and is_identity = 'YES') then
    select coalesce(max(game_number), 0) + 1 into v_next from public.games;
    execute format(
      'alter table public.games alter column game_number add generated by default as identity (start with %s)',
      v_next);
  end if;
end $$;

create unique index if not exists games_game_number_key on public.games (game_number);

comment on column public.games.game_number is
  'The game''s short number — /game/<number> (round 41). Assigned in creation '
  'order; unique; never reused. /game/<id> keeps working alongside it.';

-- -----------------------------------------------------------------------------
-- 2. dismiss_notification — one item out of the reader's own bell
-- -----------------------------------------------------------------------------

create or replace function public.dismiss_notification(p_notification_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_player_id uuid := public.current_player_id();
begin
  if v_player_id is null then
    raise exception 'INSUFFICIENT_PERMISSION' using detail = 'no player for this session';
  end if;

  -- Only a notification this reader can SEE: a broadcast, or one addressed to
  -- them. Anything else is reported as not found, which is also what it is
  -- from where they stand.
  if not exists (
    select 1 from public.notifications n
     where n.id = p_notification_id
       and (n.recipient_id is null or n.recipient_id = v_player_id)
  ) then
    raise exception 'NOTIFICATION_NOT_FOUND';
  end if;

  insert into public.user_notification_reads (player_id, notification_id, dismissed_at)
  values (v_player_id, p_notification_id, now())
      on conflict (player_id, notification_id)
      do update set dismissed_at = now();

  return true;
end;
$$;

revoke execute on function public.dismiss_notification(uuid) from public, anon;
grant execute on function public.dismiss_notification(uuid) to authenticated;

comment on function public.dismiss_notification(uuid) is
  'Removes one notification from the caller''s own bell (round 41). Per-player: '
  'the notification and everybody else''s bell are untouched.';


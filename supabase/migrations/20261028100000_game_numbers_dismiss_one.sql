-- -----------------------------------------------------------------------------
-- 4. VERIFICATION — SHAPE ONLY, and the result of the backfill above.
-- -----------------------------------------------------------------------------

do $$
declare v_caps jsonb := public.app_capabilities();
begin
  if exists (select 1 from public.games where game_number is null) then
    raise exception 'game numbers: a game has no number after the backfill';
  end if;
  if not exists (select 1 from information_schema.columns
                  where table_schema = 'public' and table_name = 'games'
                    and column_name = 'game_number' and is_identity = 'YES') then
    raise exception 'game numbers: games.game_number is not an identity';
  end if;
  if not exists (select 1 from pg_indexes
                  where schemaname = 'public' and indexname = 'games_game_number_key') then
    raise exception 'game numbers: the unique index is missing';
  end if;
  if not has_column_privilege('anon', 'public.games', 'game_number', 'select') then
    raise exception 'game numbers: anon cannot read games.game_number';
  end if;
  if not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                  where n.nspname = 'public' and p.proname = 'dismiss_notification') then
    raise exception 'dismiss one: dismiss_notification is missing';
  end if;
  if has_function_privilege('anon', 'public.dismiss_notification(uuid)', 'execute') then
    raise exception 'dismiss one: anon can execute dismiss_notification';
  end if;
  if (select count(*) from jsonb_object_keys(v_caps)) <> 33
     or exists (select 1 from jsonb_each(v_caps) where value <> 'true'::jsonb) then
    raise exception 'round 41: app_capabilities is not 33 flags, all true: %', v_caps;
  end if;
end $$;

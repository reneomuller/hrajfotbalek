-- ROUND 41 — short game links, and deleting one notification.
--
-- 1. `games.game_number` — the owner: "would it be possible for each posted
--    game to have a better looking link rather than an extremely long one?
--    ideally /game/<number>". Every game gets a number in the order it was
--    created; new games take the next one without anybody passing it.
--    `/game/<uuid>` keeps working — every link already shared stays good.
--
-- 2. `dismiss_notification(uuid)` — "add user option to delete
--    notifications". The bell has had Clear all since round 16; this takes
--    ONE item out of the reader's own bell. Like Clear all it writes the
--    per-player `dismissed_at`, so the notification itself is untouched and
--    nobody else's bell changes.
--
-- 3. `app_capabilities()` — restated as a superset of the 31 flags live on
--    2026-10-28 (probed, not copied from the last file), with this file's two.
--
-- Additive, idempotent, NOT deploy-first, order-free against everything
-- applied. The deploy is safe without it: the short link and the per-item
-- delete appear only when `app_capabilities()` says so.
--
--   node scripts/apply-migration.mjs \
--     supabase/migrations/20261028100000_game_numbers_dismiss_one.sql --production
